"""Slide colour palettes, one per domain. Colours are (r, g, b) 0-255.

``light`` is the slide background. It stays near white (luminance > 0.9) so hidden-text tests behave like
real decks: white text on it is invisible, white text on the ``primary`` title band is not.
"""

from dataclasses import dataclass

RGB = tuple[int, int, int]


@dataclass(frozen=True)
class Palette:
    primary: RGB  # title band, table header, chart bars
    dark: RGB  # body text
    light: RGB  # slide background
    accent: RGB  # bullets and highlights


